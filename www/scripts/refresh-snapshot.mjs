// Rebuilds src/market/snapshot.js from the live free sources.
// Usage: node scripts/refresh-snapshot.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  loadUstPar, loadUstBillRates, loadTreasuryAuctions, loadNyFedRates, loadSofrHistory,
  loadEcbAaaSpot, loadEcbAllSpot, loadEstr, loadBocBenchmarks, loadCorra,
} from '../src/market/feeds.js';

const AUCTION_LIMIT = 60;
const loaders = [
  loadUstPar, loadUstBillRates, loadTreasuryAuctions, loadNyFedRates, loadSofrHistory,
  loadEcbAaaSpot, loadEcbAllSpot, loadEstr, loadBocBenchmarks, loadCorra,
];

const datasets = {};
for (const load of loaders) {
  const d = await load();
  if (d.securities) d.securities = d.securities.slice(0, AUCTION_LIMIT);
  datasets[d.id] = { ...d, status: 'snapshot' };
  console.log(`${d.id.padEnd(16)} asOf ${d.asOf}`);
}

const snapshot = { capturedAt: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'), datasets };
const out = fileURLToPath(new URL('../src/market/snapshot.js', import.meta.url));
writeFileSync(
  out,
  '// Generated by scripts/refresh-snapshot.mjs. Do not edit by hand.\n' +
    `export const SNAPSHOT = ${JSON.stringify(snapshot, null, 1)};\n`,
);
console.log(`wrote ${out}`);
