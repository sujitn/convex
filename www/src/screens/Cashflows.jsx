import React from 'react';
import { useWorkspace, useComputation } from '../state/workspace';
import { useStore } from '../state/store';
import * as R from '../lib/requests';
import { CURVE_DEFS } from '../analytics/curves';
import { Panel, EngineError, Empty, Spinner, Prov } from '../ui/primitives';
import SecurityBand from '../ui/SecurityBand';
import ScreenHead from '../ui/ScreenHead';
import { BarChart } from '../ui/charts';
import { fmt, money } from '../lib/format';
import { formatLong, yearsBetween } from '../lib/dates';

async function loadCashflows(engine, sec, settlement, curve) {
  const label = sec.ticker || sec.name;
  const cf = await engine.call(R.bondCashflows(sec, settlement), { label: `${label} cash flows` });
  if (!cf.ok) return { error: cf.error };
  const byDate = new Map();
  const row = (d) => {
    if (!byDate.has(d)) byDate.set(d, { date: d, coupon: 0, principal: 0, periods: [] });
    return byDate.get(d);
  };
  for (const c of cf.data.coupons) {
    if (!c.entitled) continue;
    const r = row(c.payment_date);
    r.coupon += Number(c.amount);
    r.periods.push([c.accrual_start, c.accrual_end]);
  }
  for (const p of cf.data.principal) row(p.payment_date).principal += Number(p.amount);
  const rows = [...byDate.values()].sort((a, b) => (a.date < b.date ? -1 : 1));
  const out = { rows, outstanding: cf.data.outstanding_principal, accrued: Number(cf.data.accrued) };
  if (!curve || !curve.recipe) return out;

  // Native discount factors at each payment date and at settlement; the bond's
  // present value discounts to settlement, so the factor used is their ratio.
  const dfReqs = [settlement, ...rows.map((r) => r.date)].map((d) => R.curveQuery([curve.recipe], curve.key, R.dfQuery({ Date: d })));
  const dfs = await engine.callMany(dfReqs, { label: `${label} discount factors` });
  const bad = dfs.find((d) => !d.ok);
  if (bad) return { ...out, dfError: bad.error };
  const dfSettle = dfs[0].data.value;
  rows.forEach((r, i) => {
    r.df = dfs[i + 1].data.value / dfSettle;
    r.pv = (r.coupon + r.principal) * r.df;
  });
  const def = CURVE_DEFS[curve.id];
  const price = await engine.call(R.bondPrice(sec, settlement, R.spreadMethod(curve.key, R.governmentRole(def.benchmarkId), 0), [curve.recipe]),
    { label: `${label} PV at the curve` });
  if (price.ok) out.enginePv = price.data.present_value.value;
  else out.priceError = price.error;
  return out;
}

export default function Cashflows({ fn }) {
  const { engine, selected: sec, settlement, curve } = useWorkspace();
  const { state } = useStore();
  const face = Number(state.quote.face || '1000000');
  const ok = sec && sec.kind === 'fixed';
  const { data, busy } = useComputation(
    () => (ok && curve && !curve.building ? loadCashflows(engine, { ...sec, calls: [] }, settlement, curve) : null),
    [sec, settlement, curve && curve.key && curve.key.version, curve && curve.building],
  );
  const scale = sec ? face / Number(sec.face || 100) : 1;
  const rows = data && data.rows ? data.rows : [];
  const total = rows.reduce((a, r) => a + r.coupon + r.principal, 0);
  const pvTotal = rows.reduce((a, r) => a + (r.pv || 0), 0);

  return (
    <div className="screen">
      <ScreenHead fn={fn} lede="Entitled cash from settlement, generated by the engine from the full contract, discounted on the government curve." />
      <SecurityBand sec={sec} settlement={settlement} />
      {!ok && <Empty>Cash flows are shown for coupon bonds. Bills have a single redemption; see BILL.</Empty>}
      {ok && busy && !data && <Empty><Spinner /></Empty>}
      {data && data.error && <EngineError error={data.error} context="Cash flows" />}
      {sec && sec.calls && sec.calls.length > 0 && (
        <div className="note note--warn" style={{ marginBottom: 16 }}>Shown to maturity, assuming no call is exercised.</div>
      )}
      {rows.length > 0 && (
        <div className="stack">
          <Panel title="Cash flow profile" note={`per ${money(face, 0)} ${sec.currency} face`}>
            <BarChart height={220}
              keys={[{ key: 'coupon', label: 'Coupon', color: '--s1' }, { key: 'principal', label: 'Principal', color: '--s2' }]}
              bars={rows.map((r) => ({ x: yearsBetween(settlement, r.date), date: r.date,
                parts: [{ key: 'coupon', value: r.coupon * scale }, { key: 'principal', value: r.principal * scale }] }))}
              xFormat={(v) => `${Math.round(v)}Y`} yFormat={(v) => (Math.abs(v) >= 1000 ? `${fmt(v / 1000, 0)}k` : fmt(v, 0))}
              tipX={(v, b) => formatLong(b.date)} />
          </Panel>
          <Panel title="Schedule" flush
            foot={data.enginePv !== undefined ? (
              <span>
                Σ PV {fmt(pvTotal, 7)} per {sec.face} · engine price at Z = 0: {fmt(data.enginePv, 7)}{' '}
                <Prov status={Math.abs(pvTotal - data.enginePv) < 1e-6 ? 'live' : 'error'}>
                  {Math.abs(pvTotal - data.enginePv) < 1e-6 ? 'Reconciles' : 'Differs'}
                </Prov>
              </span>
            ) : null}>
            <div className="table-wrap" style={{ maxHeight: 520 }}>
              <table className="grid">
                <thead>
                  <tr><th>Payment</th><th>Accrual period</th><th className="num">Coupon</th><th className="num">Principal</th>
                    <th className="num">Total</th><th className="num">DF from settle</th><th className="num">PV</th></tr>
                </thead>
                <tbody>
                  {rows.map((r) => (
                    <tr key={r.date}>
                      <td>{formatLong(r.date)}</td>
                      <td className="dim">{r.periods.map(([a, b]) => `${formatLong(a)} – ${formatLong(b)}`).join(', ')}</td>
                      <td className="num">{r.coupon ? money(r.coupon * scale) : ''}</td>
                      <td className="num">{r.principal ? money(r.principal * scale) : ''}</td>
                      <td className="num">{money((r.coupon + r.principal) * scale)}</td>
                      <td className="num dim">{r.df !== undefined ? fmt(r.df, 6) : ''}</td>
                      <td className="num">{r.pv !== undefined ? money(r.pv * scale) : ''}</td>
                    </tr>
                  ))}
                </tbody>
                <tfoot>
                  <tr><td>Total</td><td /><td className="num">{money(rows.reduce((a, r) => a + r.coupon, 0) * scale)}</td>
                    <td className="num">{money(rows.reduce((a, r) => a + r.principal, 0) * scale)}</td>
                    <td className="num">{money(total * scale)}</td><td /><td className="num">{money(pvTotal * scale)}</td></tr>
                </tfoot>
              </table>
            </div>
          </Panel>
          {data.dfError && <EngineError error={data.dfError} context="Discount factors" />}
          {data.priceError && <EngineError error={data.priceError} context="Curve price" />}
        </div>
      )}
    </div>
  );
}
