#!/usr/bin/env python3
"""Export the frozen Decimal controls to a dependency-free Rust test fixture."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
REFERENCE=ROOT/'tests/fixtures/library/ufr-reference.json'
OUTPUT=ROOT/'tests/fixtures/library/ufr_reference.rs'


def content():
    data=json.loads(REFERENCE.read_bytes())
    rows=[]
    for model in data['models']+data['dated']:
        for p in model['points']:
            row=[model[k] for k in ['llp','boundary_zero','boundary_forward','ufr','alpha']]
            row += [p[k] for k in ['time','zero','forward','discount']]
            rows.append('    ['+', '.join(repr(float(x)) for x in row)+'],')
    return ('// Frozen independent Decimal(60) values; generated by ufr_math_fixture.py.\n'
            '// Original JSON SHA256: '+hashlib.sha256(REFERENCE.read_bytes()).hexdigest()+'\n'
            'pub const RATE_BOUND: f64 = '+data['bounds']['rate_absolute']+';\n'
            'pub const DISCOUNT_ABSOLUTE: f64 = '+data['bounds']['discount_absolute']+';\n'
            'pub const DISCOUNT_RELATIVE: f64 = '+data['bounds']['discount_relative']+';\n'
            '#[rustfmt::skip]\npub const POINTS: &[[f64; 9]] = &[\n'+'\n'.join(rows)+'\n];\n').encode()


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    raw=content()
    if args.check:
        if OUTPUT.read_bytes()!=raw:raise SystemExit('Original Rust UFR controls differ')
    else:
        if OUTPUT.exists():raise SystemExit('Refusing to overwrite frozen Rust controls')
        OUTPUT.write_bytes(raw)
    print(json.dumps(dict(status='passed',points=96,certified=False)))
