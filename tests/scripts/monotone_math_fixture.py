#!/usr/bin/env python3
"""Project frozen independent values into Rust without a test-only dependency."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
REFERENCE=ROOT/'tests/fixtures/library/monotone-reference.json'
OUTPUT=ROOT/'tests/fixtures/library/monotone_reference.rs'


def content():
    data=json.loads(REFERENCE.read_bytes())
    vector=lambda values: '&['+', '.join(repr(float(v)) for v in values)+']'
    rows=[]
    for model in data['models']+data['dated']:
        points=[vector([p[k] for k in ['time','zero','forward','derivative','integral','discount']])[1:]
                for p in model['points']+model.get('dated_points',[])]
        rows.append('    Model { id: '+json.dumps(model['id'])+', knots: '+vector(model['knots'])+
                    ', zeros: '+vector(model['zeros'])+', means: '+vector(model['means'])+
                    ', node_forwards: '+vector(model['node_forwards'])+', points: &[\n        '+',\n        '.join(points)+'\n    ]},')
    return ('// Frozen independent Decimal(60) controls. Generated by monotone_math_fixture.py.\n'
            '// Original JSON SHA256: '+hashlib.sha256(REFERENCE.read_bytes()).hexdigest()+'\n'
            '#![allow(dead_code)]\n'
            'pub struct Model { pub id: &\'static str, pub knots: &\'static [f64], pub zeros: &\'static [f64], '
            'pub means: &\'static [f64], pub node_forwards: &\'static [f64], pub points: &\'static [[f64; 6]] }\n'
            'pub const RATE_BOUND: f64 = '+data['bounds']['rate_absolute']+';\n'
            'pub const DERIVATIVE_BOUND: f64 = '+data['bounds']['derivative_absolute']+';\n'
            'pub const INTEGRAL_BOUND: f64 = '+data['bounds']['integral_absolute']+';\n'
            'pub const DISCOUNT_ABSOLUTE: f64 = '+data['bounds']['discount_absolute']+';\n'
            'pub const DISCOUNT_RELATIVE: f64 = '+data['bounds']['discount_relative']+';\n'
            '#[rustfmt::skip]\npub const MODELS: &[Model] = &[\n'+'\n'.join(rows)+'\n];\n').encode()


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    raw=content()
    if args.check:
        if OUTPUT.read_bytes()!=raw:raise SystemExit('Original Rust monotone controls differ')
    else:
        if OUTPUT.exists():raise SystemExit('Refusing to overwrite frozen Rust controls')
        OUTPUT.write_bytes(raw)
    print(json.dumps(dict(status='passed',certified=False)))
